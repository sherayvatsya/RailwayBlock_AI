export const calculateTaskScoreAndPriority = (
  urgency: UrgencyLevel,
  criticality: AssetCriticality,
  overdue: boolean
): { score: number; priority: PriorityLevel } => {
  let score = 0;

  // Urgency weights
  if (urgency === 'High') score += 40;
  else if (urgency === 'Medium') score += 25;
  else score += 10;

  // Asset Criticality weights
  if (criticality === 'Very High') score += 45;
  else if (criticality === 'High') score += 30;
  else if (criticality === 'Medium') score += 15;
  else score += 5;

  // Overdue penalty / bonus
  if (overdue) score += 25;

  let priority: PriorityLevel = 'Low';
  if (score >= 80) priority = 'Critical';
  else if (score >= 60) priority = 'High';
  else if (score >= 35) priority = 'Medium';
  else priority = 'Low';

  return { score, priority };
};

